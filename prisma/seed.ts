async function main() {
    console.log('Очистка старых данных...');
    await prisma.libraryItem.deleteMany();
    await prisma.review.deleteMany();
    await prisma.book.deleteMany();
    await prisma.user.deleteMany();

    const demoUser = await prisma.user.create({
        data: {
            email: 'reader@example.com',
            name: 'Алексей Читатель',
            passwordHash: hashPassword('123456'),
        },
    });

    const secondUser = await prisma.user.create({
        data: {
            email: 'anna@example.com',
            name: 'Анна Книголюб',
            passwordHash: hashPassword('123456'),
        },
    });

    const createdBooks = [];

    for (let i = 0; i < CATALOG.length; i++) {
        const item = CATALOG.at(i)!;
        const title = item.at(0) as string;
        const author = item.at(1) as string;
        const genre = item.at(2) as string;
        const publishedYear = item.at(3) as number;
        const description = item.at(4) as string;

        const coverUrl = COVERS.at(i % COVERS.length)!;
        const audioUrl = i % 3 === 0 ? AUDIO_SAMPLES.at(i % AUDIO_SAMPLES.length)! : null;

        const created = await prisma.book.create({
            data: {
                title,
                author,
                genre,
                publishedYear,
                coverUrl,
                audioUrl,
                description,
                content: buildReaderContent(title, author, description),
            },
        });
        createdBooks.push(created);
    }

    // Добавляем отзывы к популярным книгам
    await prisma.review.createMany({
        data: [
            {
                rating: 5,
                comment: 'Потрясающая атмосфера Арракиса! Прочитал на одном дыхании и послушал аудиофрагмент.',
                userId: demoUser.id,
                bookId: createdBooks.at(0)!.id,
            },
            {
                rating: 5,
                comment: 'Очень практичная книга по психологии, внедрил правило двух минут в тот же день.',
                userId: secondUser.id,
                bookId: createdBooks.at(30)!.id,
            },
            {
                rating: 5,
                comment: 'Бессмертная классика! Читалка на сайте работает быстро и удобно.',
                userId: demoUser.id,
                bookId: createdBooks.at(50)!.id,
            },
            {
                rating: 4,
                comment: 'Отличный детектив, развязка держит в напряжении до конца.',
                userId: secondUser.id,
                bookId: createdBooks.at(20)!.id,
            },
        ],
    });

    // Добавляем книги в личную библиотеку демо-пользователя
    await prisma.libraryItem.createMany({
        data: [
            { status: 'READING', userId: demoUser.id, bookId: createdBooks.at(0)!.id },
            { status: 'WANT_TO_READ', userId: demoUser.id, bookId: createdBooks.at(50)!.id },
            { status: 'FINISHED', userId: demoUser.id, bookId: createdBooks.at(30)!.id },
        ],
    });

    console.log('Готово! В локальную SQLite сохранено книг: ' + createdBooks.length);
}

main()
    .catch((e) => {
        console.error(e);
        process.exit(1);
    })
    .finally(async () => {
        await prisma.$disconnect();
    });
